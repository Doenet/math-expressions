//! The exact-constant ring [`Exact`] and its arithmetic.
//!
//! A value is a ℚ-linear combination of the basis monomials `π^i · e^j · √r`
//! where `r` is a squarefree positive integer (`r = 1` ⇒ no surd). Those
//! monomials are linearly independent over ℚ: the surds `{√r : r squarefree}`
//! are ℚ-linearly independent (a standard result), and π, e are transcendental
//! (their algebraic independence from the surds — and, as every CAS assumes,
//! from each other — is taken as given). Hence the combination is zero **iff**
//! every coefficient is zero, which is exactly [`Exact::is_zero`].
//!
//! Multiplication stays in the ring because `√r · √s` re-normalizes to a
//! rational multiple of a single surd (`√12 = 2√3`); see [`mul_surd`].

use std::collections::BTreeMap;

use num_bigint::BigInt;
use num_integer::Integer;
use num_rational::BigRational;
use num_traits::{One, ToPrimitive, Zero};

use crate::expr::Expr;
use crate::num::Number;

/// A basis monomial `π^pi · e^e · √rad`. `rad` is a squarefree integer ≥ 1
/// (`rad == 1` means no surd factor).
type Mono = (u32, u32, BigInt);

/// An element of ℚ[π, e] ⊗ (ℚ-span of surds), as a sparse map from basis
/// monomial to rational coefficient. Zero coefficients are pruned, so the
/// value is zero exactly when the map is empty.
#[derive(Clone, Debug, Default)]
pub struct Exact {
    terms: BTreeMap<Mono, BigRational>,
}

impl Exact {
    pub(super) fn zero() -> Exact {
        Exact::default()
    }

    /// The rational `q` (as `q · π^0 e^0 √1`).
    pub(super) fn rat(q: BigRational) -> Exact {
        let mut t = BTreeMap::new();
        if !q.is_zero() {
            t.insert((0, 0, BigInt::one()), q);
        }
        Exact { terms: t }
    }

    /// A single monomial `coeff · π^pi · e^e · √rad` (rad already squarefree).
    pub(super) fn mono(coeff: BigRational, pi: u32, e: u32, rad: BigInt) -> Exact {
        let mut t = BTreeMap::new();
        if !coeff.is_zero() {
            t.insert((pi, e, rad), coeff);
        }
        Exact { terms: t }
    }

    /// `coeff · √rad` for a rad that is **already squarefree** (the lattice
    /// tables pass literals 2/3/6; `eval_sqrt` passes the squarefree part it
    /// just computed). No factoring, no panic path — callers that hold a
    /// possibly-square-divisible radicand must go through [`squarefree_part`]
    /// first.
    pub(super) fn surd(coeff: BigRational, squarefree_rad: u128) -> Exact {
        Exact::mono(coeff, 0, 0, BigInt::from(squarefree_rad))
    }

    pub fn is_zero(&self) -> bool {
        self.terms.is_empty()
    }

    pub(super) fn add(&self, other: &Exact) -> Exact {
        let mut terms = self.terms.clone();
        for (k, v) in &other.terms {
            let e = terms.entry(k.clone()).or_insert_with(BigRational::zero);
            *e += v;
            if e.is_zero() {
                terms.remove(k);
            }
        }
        Exact { terms }
    }

    pub(super) fn neg(&self) -> Exact {
        Exact {
            terms: self.terms.iter().map(|(k, v)| (k.clone(), -v)).collect(),
        }
    }

    pub(super) fn mul(&self, other: &Exact, budget: &mut i64) -> Option<Exact> {
        let mut acc = Exact::zero();
        for ((p1, e1, r1), c1) in &self.terms {
            for ((p2, e2, r2), c2) in &other.terms {
                spend(budget)?;
                let (coeff, rad) = mul_surd(c1 * c2, r1, r2);
                let mono = Exact::mono(coeff, p1 + p2, e1 + e2, rad);
                acc = acc.add(&mono);
            }
        }
        Some(acc)
    }

    /// This value as a plain rational, if it has no π/e/surd part.
    pub(super) fn as_rational(&self) -> Option<BigRational> {
        match self.terms.len() {
            0 => Some(BigRational::zero()),
            1 => {
                let ((p, e, r), c) = self.terms.iter().next().unwrap();
                (*p == 0 && *e == 0 && r.is_one()).then(|| c.clone())
            }
            _ => None,
        }
    }

    /// The rational `p` such that `self == p · π` (only the `π^1` monomial),
    /// or `0` when `self` is zero. `None` if any other component is present.
    pub(super) fn as_pi_multiple(&self) -> Option<BigRational> {
        let mut p = BigRational::zero();
        for ((pi, e, r), c) in &self.terms {
            if *pi == 1 && *e == 0 && r.is_one() {
                p = c.clone();
            } else {
                return None;
            }
        }
        Some(p)
    }

    /// `1/self` for a nonzero element of the multiquadratic part of the ring —
    /// ℚ(√r₁, √r₂, …), with no π or e factor. `None` for zero, and for
    /// anything carrying a transcendental generator (`1/(1+π)` is not a
    /// polynomial in π, so it is simply not in this ring).
    ///
    /// The recursion is conjugate rationalization. Pick a prime `p` dividing
    /// one of the radicands and write `self = A + √p·B`, where `A` and `B` live
    /// in the subfield generated by the *remaining* primes (a term `c·√r` with
    /// `p | r` contributes `c·√(r/p)` to `B`; `r` is squarefree, so `r/p` is
    /// again coprime to `p`). Then
    ///
    /// ```text
    /// 1/(A + √p·B) = (A − √p·B) / (A² − p·B²)
    /// ```
    ///
    /// and the denominator involves strictly fewer primes, so the recursion
    /// bottoms out at a rational. `A² − p·B² = 0` would put `√p = A/B` inside
    /// that smaller subfield, which it is not, so for nonzero `self` the
    /// denominator is nonzero; the `?` below is belt-and-braces.
    ///
    /// Before this was general, the reciprocal trig functions declined at half
    /// the lattice — `sec(π/12) = 4/(√6+√2)` has a two-term denominator — even
    /// though the value, `√6−√2`, is in the ring.
    pub(super) fn inverse(&self, budget: &mut i64) -> Option<Exact> {
        if let Some(q) = self.as_rational() {
            return (!q.is_zero()).then(|| Exact::rat(BigRational::one() / q));
        }
        if self.terms.keys().any(|(p, e, _)| *p != 0 || *e != 0) {
            return None;
        }
        spend(budget)?;
        let p = self.some_radicand_prime(budget)?;
        let (a, b) = self.split_off_sqrt(&p);
        let b2 = b.mul(&b, budget)?;
        let denom = a.mul(&a, budget)?.add(
            &b2.mul(&Exact::rat(BigRational::from_integer(p.clone())), budget)?
                .neg(),
        );
        let numer = a.add(
            &b.mul(&Exact::mono(BigRational::one(), 0, 0, p), budget)?
                .neg(),
        );
        numer.mul(&denom.inverse(budget)?, budget)
    }

    /// A prime dividing one of the radicands, for [`inverse`](Self::inverse) to
    /// split on. `None` when every term is rational, or when factoring the
    /// radicand would exceed the trial-division budget.
    fn some_radicand_prime(&self, budget: &mut i64) -> Option<BigInt> {
        let r = self.terms.keys().map(|(_, _, r)| r).find(|r| !r.is_one())?;
        smallest_prime_factor(r, budget)
    }

    /// Split `self` as `A + √p·B` with `A`, `B` free of `√p` (see
    /// [`inverse`](Self::inverse)). Radicands are squarefree, so `p` divides a
    /// radicand at most once and the split is exact.
    fn split_off_sqrt(&self, p: &BigInt) -> (Exact, Exact) {
        let mut a = BTreeMap::new();
        let mut b = BTreeMap::new();
        for ((pi, e, r), c) in &self.terms {
            if (r % p).is_zero() {
                b.insert((*pi, *e, r / p), c.clone());
            } else {
                a.insert((*pi, *e, r.clone()), c.clone());
            }
        }
        (Exact { terms: a }, Exact { terms: b })
    }

    /// This value as a canonical expression — the inverse direction of
    /// [`exact_eval`](super::exact_eval), used to emit exact special values
    /// such as `sin(pi/6) → 1/2`, `sec(pi/4) → sqrt(2)`, etc.
    pub(crate) fn to_expr(&self) -> Expr {
        if self.terms.is_empty() {
            return Expr::int(0);
        }
        let mut terms = Vec::with_capacity(self.terms.len());
        for ((pi, e, rad), c) in &self.terms {
            let mut factors: Vec<Expr> = vec![Expr::Num(Number::from_bigrational(c.clone()))];
            // π/e are emitted as `Sym` — the canonical spelling. (`Const(Pi)`
            // exists as a variant, but the parsers only produce `Sym`, and
            // canonicalize unifies `Const(Pi/E/I)` → `Sym`; minting `Sym`
            // directly keeps this output canonical without a re-pass.)
            if *pi > 0 {
                factors.push(crate::normalize::pow(
                    Expr::sym("pi"),
                    Expr::int(i64::from(*pi)),
                ));
            }
            if *e > 0 {
                factors.push(crate::normalize::pow(
                    Expr::sym("e"),
                    Expr::int(i64::from(*e)),
                ));
            }
            if !rad.is_one() {
                let radn = Expr::Num(Number::from_bigrational(BigRational::from_integer(
                    rad.clone(),
                )));
                // `sqrt(rad)` (an `Apply`), not `rad^(1/2)` (a `Pow`): the
                // former is the canonical surd spelling the parsers/simplify
                // use, so `to_expr` output unifies with the rest of the system
                // (e.g. `full_simplify(cos(π/6))` == `sqrt(3)/2`).
                factors.push(Expr::Apply(Box::new(Expr::sym("sqrt")), vec![radn]));
            }
            terms.push(crate::normalize::mul(factors));
        }
        crate::normalize::canonicalize(&crate::normalize::add(terms))
    }

    pub(super) fn pow_int(&self, k: i64, budget: &mut i64) -> Option<Exact> {
        if k == 0 {
            return Some(Exact::rat(BigRational::one()));
        }
        let base = if k < 0 {
            self.inverse(budget)?
        } else {
            self.clone()
        };
        let mut acc = Exact::rat(BigRational::one());
        for _ in 0..k.unsigned_abs() {
            spend(budget)?;
            acc = acc.mul(&base, budget)?;
        }
        Some(acc)
    }
}

/// `coeff · √r1 · √r2` re-normalized to `(coeff', r')` with `r'` squarefree.
///
/// By gcd, not by factoring. With `g = gcd(r1, r2)`, `r1 = g·a` and `r2 = g·b`,
/// `√r1·√r2 = g·√(ab)` — and `ab` needs no square-part extraction, because it
/// is already squarefree. `r1` squarefree forces `gcd(g, a) = 1` (a common
/// prime would put `p²` in `r1`), and likewise `gcd(g, b) = 1`, so a prime
/// dividing both `a` and `b` would have to divide `g` and contradict one of
/// those. `a` and `b` are thus coprime, and each is squarefree as a divisor of
/// one.
///
/// Reaching for [`squarefree_part`] of the product instead — which is what this
/// did — trial-divides up to `√(r1·r2)`, and [`Exact::inverse`] pays that on
/// every one of the `2^k` term pairs it multiplies out. A gcd is logarithmic
/// and exact, so the whole cost disappears rather than being budgeted for.
fn mul_surd(coeff: BigRational, r1: &BigInt, r2: &BigInt) -> (BigRational, BigInt) {
    if r1.is_one() {
        return (coeff, r2.clone());
    }
    if r2.is_one() {
        return (coeff, r1.clone());
    }
    let g = r1.gcd(r2);
    let rad = (r1 / &g) * (r2 / &g);
    (coeff * BigRational::from_integer(g), rad)
}

/// The smallest prime factor of `n > 1`, by trial division under the same cap
/// as [`squarefree_part`] (`None` if the cap is hit first — a radicand whose
/// factorization is out of reach makes the caller decline, never stall). `n`
/// itself when the division runs past `√n`, which proves it prime.
fn smallest_prime_factor(n: &BigInt, budget: &mut i64) -> Option<BigInt> {
    let m = n.to_u128()?;
    let cap = u128::from(crate::resource_limits::current().max_squarefree_trial_divisor);
    let mut d: u128 = 2;
    while d.checked_mul(d).is_some_and(|dd| dd <= m) {
        spend(budget)?;
        if m.is_multiple_of(d) {
            return Some(BigInt::from(d));
        }
        d += 1;
        if d > cap {
            return None;
        }
    }
    Some(n.clone())
}

/// Write `m = s²·f` with `f` squarefree; return `(s, f)`. `None` if `m` is 0
/// or its square-factoring would exceed the trial-division budget.
///
/// Every divisor tried is charged to the shared op budget, so that the budget
/// bounds trial division too and not just node count. `max_squarefree_trial_divisor`
/// caps a single *call* at millions of divisions, which says nothing about an
/// expression that makes many: `√p₁ + … + √p₁₀₀` over large primes is one
/// unremarkable input holding a hundred of them. The one caller left is
/// `eval_sqrt` — [`mul_surd`] used to be the other, and dropping it from there
/// is what made this charge affordable.
///
/// The charge sets the reach: a squarefree radicand much past `max_exact_eval_ops²`
/// (~10⁸ by default) exhausts the budget before the scan reaches `√m`, so
/// `√1000000000039` is undecided in the exact tower. Nothing is *answered*
/// differently — `equals` decides such a comparison numerically, as it already
/// did for the radicands past `max_squarefree_trial_divisor²` that this has
/// always declined.
pub(super) fn squarefree_part(mut m: u128, budget: &mut i64) -> Option<(u128, u128)> {
    if m == 0 {
        return None;
    }
    let mut s: u128 = 1;
    let mut d: u128 = 2;
    while let Some(dd) = d.checked_mul(d) {
        if dd > m {
            break;
        }
        spend(budget)?;
        while m.is_multiple_of(dd) {
            m /= dd;
            s = s.checked_mul(d)?;
        }
        d += 1;
        // Cap trial division so a large near-prime radicand can't stall us —
        // §7f-governed like every other unpredictable-cost bound.
        if d > u128::from(crate::resource_limits::current().max_squarefree_trial_divisor) {
            return None;
        }
    }
    Some((s, m))
}

/// Decrement the shared operation budget; `None` once it is exhausted.
pub(super) fn spend(budget: &mut i64) -> Option<()> {
    *budget -= 1;
    (*budget >= 0).then_some(())
}
